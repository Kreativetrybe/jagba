// Generates Sources/WordmarkPaths.swift: the JaGBa "Shelter" lockup as path
// data, built from Ojuju 800's real letter outlines (design/ojuju-glyphs.json).
// The geometry matches design/jagba.html. Run: node tools/make-wordmark.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const { glyphs } = JSON.parse(fs.readFileSync(path.join(root, "design/ojuju-glyphs.json"), "utf8"));

// Point on the edge p→q at height y.
const on = (p, q, y) => [p[0] + (q[0] - p[0]) * (y - p[1]) / (q[1] - p[1]), y];

// Shelter: one row; the capitals lean in over the small a's.
const base = 470, xh = 226;
const J = [[50, 146], [194, 128], [150, base], [56, base]];
const G = [[228, 120], [372, 126], [366, base], [270, base]];
const B = [[372, 126], [530, 132], [482, base], [366, base]];
const a1 = [on(J[1], J[2], xh), on(G[0], G[3], xh), G[3], J[2]];
const a2 = [on(B[1], B[2], xh), [592, xh + 4], [596, base], B[2]];
const cells = [["J", J], ["a", a1], ["G", G], ["B", B], ["a", a2]];

function flatten(d) {
  const tok = d.match(/[MLHVQCZ]|-?\d*\.?\d+(?:e-?\d+)?/g);
  const contours = []; let cur = null, i = 0, pen = [0, 0], cmd = null;
  const num = () => parseFloat(tok[i++]);
  while (i < tok.length) {
    if (/[MLHVQCZ]/.test(tok[i])) cmd = tok[i++];
    if (cmd === "M") { pen = [num(), num()]; cur = [pen]; contours.push(cur); cmd = "L"; }
    else if (cmd === "L") { pen = [num(), num()]; cur.push(pen); }
    else if (cmd === "H") { pen = [num(), pen[1]]; cur.push(pen); }
    else if (cmd === "V") { pen = [pen[0], num()]; cur.push(pen); }
    else if (cmd === "Q") {
      const c = [num(), num()], e = [num(), num()], s = pen;
      for (let k = 1; k <= 8; k++) { const t = k / 8, m = 1 - t; cur.push([m * m * s[0] + 2 * m * t * c[0] + t * t * e[0], m * m * s[1] + 2 * m * t * c[1] + t * t * e[1]]); }
      pen = e;
    } else if (cmd === "Z") { cmd = null; }
  }
  return contours.map(c => c.flatMap((pt, j) => {
    const nx = c[(j + 1) % c.length], out = [pt], n = Math.ceil(Math.hypot(nx[0] - pt[0], nx[1] - pt[1]) / 25);
    for (let k = 1; k < n; k++) out.push([pt[0] + (nx[0] - pt[0]) * k / n, pt[1] + (nx[1] - pt[1]) * k / n]);
    return out;
  }));
}

function cellContours(glyph, [tl, tr, br, bl]) {
  const [x0, y0, x1, y1] = glyph.bounds;
  return flatten(glyph.d).map(c => c.map(([x, y]) => {
    const u = (x - x0) / (x1 - x0), v = (y1 - y) / (y1 - y0);
    const a = (1 - u) * (1 - v), b = u * (1 - v), cc = u * v, d = (1 - u) * v;
    return [a * tl[0] + b * tr[0] + cc * br[0] + d * bl[0], a * tl[1] + b * tr[1] + cc * br[1] + d * bl[1]];
  }));
}

const letters = cells.map(([ch, cell]) => cellContours(glyphs[ch], cell));
const all = letters.flat(2);
const minX = Math.min(...all.map(p => p[0])), minY = Math.min(...all.map(p => p[1]));
const maxX = Math.max(...all.map(p => p[0])), maxY = Math.max(...all.map(p => p[1]));
const toPath = contours => contours.map(c => "M" + c.map(p => (p[0] - minX).toFixed(1) + " " + (p[1] - minY).toFixed(1)).join("L") + "Z").join("");

const swift = `// Generated by tools/make-wordmark.js. Do not edit by hand.
// The JaGBa "Shelter" wordmark: Ojuju 800 letter outlines, warped so the
// capitals lean over the lowercase a's. One path per letter, in reading order.
import CoreGraphics

enum WordmarkPaths {
    static let size = CGSize(width: ${(maxX - minX).toFixed(1)}, height: ${(maxY - minY).toFixed(1)})
    static let letters: [String] = [
${letters.map(l => `        "${toPath(l)}",`).join("\n")}
    ]
}
`;
fs.writeFileSync(path.join(root, "Sources/WordmarkPaths.swift"), swift);

// The same lockup as an SVG for the download page (bone letters, charcoal cuts).
const w = (maxX - minX).toFixed(1), h = (maxY - minY).toFixed(1);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-6 -6 ${(+w + 12).toFixed(1)} ${(+h + 12).toFixed(1)}" role="img" aria-label="JAGBA">` +
  letters.map(l => `<path d="${toPath(l)}" fill="#D9CBB8" stroke="#1E1C1A" stroke-width="9" stroke-linejoin="round" paint-order="stroke fill"/>`).join("") + `</svg>\n`;
fs.mkdirSync(path.join(root, "docs"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/wordmark.svg"), svg);
console.log("wrote Sources/WordmarkPaths.swift", (maxX - minX).toFixed(1), "x", (maxY - minY).toFixed(1), Math.round(swift.length / 1024) + " KB");
